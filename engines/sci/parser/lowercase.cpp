bool parserLanguageIsDoubleByte(Common::Language language) {
	// Korean SCI text is bare EUC-KR: GfxText16::SwitchToFont1001OnKorean()
	// sniffs the raw bytes rather than looking for a language splitter, so
	// this is the same encoding the tokenizer is handed.
	//
	// Japanese is deliberately NOT here even though its text is Shift-JIS and
	// the same table damages it. See the reasons recorded next to the
	// Japanese entry in test/engines/sci/parser_lowercase.h; changing the
	// Japanese fold needs a Japanese game to check it against, and none was
	// available.
	return language == Common::KO_KOR;
}

bool parserIsLeadByte(byte c, Common::Language language) {
	if (language != Common::KO_KOR)
		return false;

	// EUC-KR: both bytes of a double-byte character are 0xA1..0xFE. This is
	// the range GfxFontKorean::isDoubleByte() uses to decide the same
	// question while drawing, so what the parser keeps intact and what the
	// font draws as one character agree.
	return c >= 0xA1 && c <= 0xFE;
}

void parserLowerCaseWord(byte *word, uint len, Common::Language language) {
	// The Russian fan translations put their vocabulary in the high half of
	// CP866 and pick the fold to match. CP866 is single-byte, so the
	// double-byte walk below never applies to it.
	const byte *lcMap = (language == Common::RU_RUS) ? lowerCaseMap866 : lowerCaseMap;
	const bool doubleByte = parserLanguageIsDoubleByte(language);

	for (uint i = 0; i < len; ++i) {
		// A lead byte and the byte after it are one character. Folding
		// either half through a single-byte table rewrites the character:
		// in EUC-KR the entry 0xA5 -> 0xA4 turns 25 ordinary syllables into
		// different ones, and the lookup that follows then searches for a
		// word the player did not type.
		if (doubleByte && parserIsLeadByte(word[i], language) && i + 1 < len) {
			++i;
			continue;
		}

		word[i] = lcMap[word[i]];
	}
}

