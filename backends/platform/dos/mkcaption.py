#!/usr/bin/env python3
"""Bake the DOS loading screen's Korean caption into loading-caption.h.

The loading screen shows before any font is read, so its one line of
Korean is drawn from a 1bpp bitmap compiled into the executable. This
renders that line from an SVFN v2 font (the 1bpp KO2350.SVF the DOS
package ships) with the font's own advances, trims it to its ink and
writes it as a C array, MSB first, rows padded to a byte.

    python3 backends/platform/dos/mkcaption.py \
        dists/engine-data/hires_text/dos/KO2350.SVF > backends/platform/dos/loading-caption.h
"""
