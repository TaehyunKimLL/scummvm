def explode(src, size):
    """Decompress the DCL data SRC to exactly SIZE bytes; ValueError when it
    is corrupt."""
    state = [0, 0, 0]  # read position, bit buffer, bits in the buffer

    def bits(n):
        while state[2] < n:
            state[1] |= (src[state[0]] if state[0] < len(src) else 0) << state[2]
            state[0] += 1
            state[2] += 8
        v = state[1] & ((1 << n) - 1)
        state[1] >>= n
        state[2] -= n
        return v

    def huff(table):
        path = ""
        while path not in table:
            path += "1" if bits(1) else "0"
            if len(path) > 16:
                raise ValueError("bad DCL code")
        return table[path]

    mode, dict_bits = bits(8), bits(8)
    if mode not in (0, 1) or dict_bits not in (4, 5, 6):
        raise ValueError("bad DCL header")
    out = bytearray()
    while len(out) < size:
        if bits(1):
            v = huff(LENGTH_CODES)
            length = v + 2 if v < 8 else 8 + (1 << (v - 7)) + bits(v - 7)
            if length == 519:
                break
            v = huff(DISTANCE_CODES)
            dist = ((v << 2) | bits(2)) if length == 2 else ((v << dict_bits) | bits(dict_bits))
            dist += 1
            if dist > len(out):
                raise ValueError("bad DCL distance")
            for _ in range(length):
                out.append(out[-dist])
        else:
            out.append(huff(ASCII_CODES) if mode else bits(8))
    return bytes(out[:size])
