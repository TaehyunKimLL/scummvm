"""Writes the SVF test data of test/graphics from the svf-fonts-open submodule.

  mkgolden.py            writes test/graphics/svf_fixture.h and test/graphics/svf_golden.h... (see OUTPUTS)
  mkgolden.py --check    regenerates both in memory and exits 1 if a committed file differs

The faces are made by the submodule's tools/svf_synth.py; the golden lines are drawn by its tools/svfline.py, the
reference the C renderer matches byte for byte.
"""
