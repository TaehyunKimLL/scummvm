def commit():
	return subprocess.run(["git", "-C", SVF, "rev-parse", "HEAD"], check=True, capture_output=True, text=True).stdout.strip()


def make_faces(tmp):
	jamo = os.path.join(tmp, "JAMO.SVF")
	marks = os.path.join(tmp, "MARKS.SVF")
	synth = os.path.join(SVF, "tools", "svf_synth.py")
	subprocess.run([sys.executable, synth, "--jmap-variant", "hybrid1", "--from", os.path.join(SVF, "svf", "dos", "NEODG16G.SVF"), jamo], check=True)
	subprocess.run([sys.executable, synth, "--marks", marks], check=True)
	return marks, jamo


def c_bytes(data, indent="\t"):
	lines = []
	for i in range(0, len(data), 16):
		lines.append(indent + ", ".join("0x%02x" % b for b in data[i:i + 16]) + ",")
	return "\n".join(lines)


def c_text(b):
	return '"' + "".join(chr(c) if 0x20 <= c < 0x7f and c not in (0x22, 0x5c, 0x3f) else "\\x%02x\"\"" % c for c in b) + '"'


def fixture_h(rev, marks, jamo):
	out = [HEADER % rev, "#ifndef TEST_GRAPHICS_SVF_FIXTURE_H", "#define TEST_GRAPHICS_SVF_FIXTURE_H", "",
	       "#include \"common/scummsys.h\"", ""]
	for name, path, note in (
			("kSvfFixtureMarks", marks, "svf_synth.py --marks: synthetic glyphs (A, e, U+FFFD, U+0300, U+0301) drawn by the\n"
			 "// tool itself, no font source; MIT like the rest of svf-fonts-open."),
			("kSvfFixtureJamo", jamo, "svf_synth.py --jmap-variant hybrid1 --from svf/dos/NEODG16G.SVF: a 16x16 1 bpp jamo face\n"
			 "// with a JSET version 3 (JMAP) block over a version 1 fallback. Font data: a Modified Version of Neo Dunggeunmo,\n"
			 "// Copyright (c) 2017-2021, Eunbin Jeong (Dalgona.) <project-neodgm@dalgona.dev>, SIL Open Font License 1.1\n"
			 "// (LICENSES/COPYING.OFL; Reserved Font Names: see dists/svf-fonts-open/svf/dos/NEODGM.TXT).")):
		data = open(path, "rb").read()
		out.append("// %s (%d bytes, sha256 %s)" % (name, len(data), hashlib.sha256(data).hexdigest()))
		out.append("// " + note)
		out.append("static const byte %s[%d] = {" % (name, len(data)))
		out.append(c_bytes(data))
		out.append("};")
		out.append("")
	out.append("#endif")
	return "\n".join(out) + "\n"


def golden_h(rev, marks, jamo):
	out = [HEADER % rev, "#ifndef TEST_GRAPHICS_SVF_GOLDEN_DATA_H", "#define TEST_GRAPHICS_SVF_GOLDEN_DATA_H", "",
	       "#include \"common/scummsys.h\"", "",
	       "// GRAY8 lines of tools/svfline.py over the chain { kSvfFixtureMarks, kSvfFixtureJamo }: one hex byte a pixel,",
	       "// one string a row.", ""]
	chain = [marks, jamo]
	for name, text, x, y, w, h, scale, missing in CASES:
		gray = svfline.layout(chain, text, x, y, w, h, missing_advance=missing, scale=scale)
		width, asc, desc = svfline.measure(chain, text, missing_advance=missing, scale=scale)
		p = "kSvfGolden" + name
		out.append("static const char %sText[] = %s;" % (p, c_text(text)))
		out.append("static const int %sX = %d, %sY = %d, %sW = %d, %sH = %d;" % (p, x, p, y, p, w, p, h))
		out.append("static const int %sScaleNum = %d, %sScaleDen = %d, %sMissing = %d;" % (p, scale[0], p, scale[1], p, missing))
		out.append("static const int %sWidth = %d, %sAscent = %d, %sDescent = %d;" % (p, width, p, asc, p, desc))
		out.append("static const char *const %sRows[%d] = {" % (p, h))
		for r in range(h):
			out.append("\t\"" + gray[r * w:(r + 1) * w].hex() + "\",")
		out.append("};")
		out.append("")
	out.append("#endif")
	return "\n".join(out) + "\n"


