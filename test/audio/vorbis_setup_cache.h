Audio::SeekableAudioStream *openClip(const Clip &c) {
	Common::String s(c.b64);
	Common::SeekableReadStream *in = Common::b64DecodeStream(s, c.size);
	if (!in)
		return nullptr;
	return Audio::makeVorbisStream(in, DisposeAfterUse::YES);
}

// Reads what is left of the stream in chunks of n samples.
Common::Array<int16> readAll(Audio::AudioStream *s, int n = 1000) {
	Common::Array<int16> out;
	int16 buf[4096];
	assert(n <= 4096);
	for (;;) {
		const int got = s->readBuffer(buf, n);
		for (int i = 0; i < got; ++i)
			out.push_back(buf[i]);
		if (got < n || s->endOfData())
			break;
	}
	return out;
}

Common::Array<int16> decodeClip(const Clip &c) {
	Audio::SeekableAudioStream *s = openClip(c);
	Common::Array<int16> out;
	if (s)
		out = readAll(s);
	delete s;
	return out;
}

// Seeks to a few places (and back to the start) and reads some samples after
// each, the way a looping or resumed speech line would.
Common::Array<int16> seekTrace(const Clip &c) {
	static const int kFrames[] = { 0, 2756, 5512, 811, 0, 8000, 4410, 0 };
	Audio::SeekableAudioStream *s = openClip(c);
	Common::Array<int16> out;
	if (!s)
		return out;
	const int ch = s->isStereo() ? 2 : 1;
	int16 buf[700 * 2];
	for (uint i = 0; i < ARRAYSIZE(kFrames); ++i) {
		out.push_back(s->seek(Audio::Timestamp(0, kFrames[i], s->getRate())) ? 1 : 0);
		const int got = s->readBuffer(buf, 700 * ch);
		out.push_back(got);
		for (int j = 0; j < got; ++j)
			out.push_back(buf[j]);
	}
	s->rewind();
	Common::Array<int16> rest = readAll(s, 333);
	out.push_back(rest.size());
	for (uint j = 0; j < rest.size(); ++j)
		out.push_back(rest[j]);
	out.push_back(s->getLength().totalNumberOfFrames());
	delete s;
	return out;
}

