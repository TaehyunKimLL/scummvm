	void test_streams_sharing_a_setup_decode_interleaved() {
#ifdef VORBIS_SETUP_CACHE_TESTS
		Audio::VorbisSetupCache::setEnabled(false);
		const Common::Array<int16> plain1 = decodeClip(kA1), plain2 = decodeClip(kA2);
		Audio::VorbisSetupCache::setEnabled(true);
		Audio::SeekableAudioStream *s1 = openClip(kA1);
		Audio::SeekableAudioStream *s2 = openClip(kA2);
		TS_ASSERT(s1 && s2);
		if (!s1 || !s2)
			return;
		TS_ASSERT_EQUALS(Audio::VorbisSetupCache::getStats().hits, 1u);
		Common::Array<int16> got1, got2;
		int16 buf[500];
		for (int i = 0; i < 6; ++i) {
			int n = s1->readBuffer(buf, 500);
			for (int j = 0; j < n; ++j)
				got1.push_back(buf[j]);
			n = s2->readBuffer(buf, 500);
			for (int j = 0; j < n; ++j)
				got2.push_back(buf[j]);
		}
		// The cache lets go of the setup and the first stream ends: the
		// second one still has it.
		Audio::VorbisSetupCache::clear();
		Common::Array<int16> rest1 = readAll(s1);
		delete s1;
		Common::Array<int16> rest2 = readAll(s2);
		delete s2;
		for (uint j = 0; j < rest1.size(); ++j)
			got1.push_back(rest1[j]);
		for (uint j = 0; j < rest2.size(); ++j)
			got2.push_back(rest2[j]);
		TS_ASSERT(got1 == plain1);
		TS_ASSERT(got2 == plain2);
#endif
	}

	void test_capacity_evicts_least_recently_used() {
#ifdef VORBIS_SETUP_CACHE_TESTS
		Audio::VorbisSetupCache::setCapacity(2);
		delete openClip(kA1);	// miss: A
		delete openClip(kB);	// miss: A B
		delete openClip(kA2);	// hit A: B A
		delete openClip(kC);	// miss, drops B: A C
		TS_ASSERT_EQUALS(Audio::VorbisSetupCache::getStats().entries, 2u);
		delete openClip(kA3);	// hit
		TS_ASSERT_EQUALS(Audio::VorbisSetupCache::getStats().hits, 2u);
		Audio::SeekableAudioStream *b = openClip(kB);	// miss again
		TS_ASSERT_EQUALS(Audio::VorbisSetupCache::getStats().misses, 4u);
		TS_ASSERT_EQUALS(Audio::VorbisSetupCache::getStats().entries, 2u);
		Audio::VorbisSetupCache::setEnabled(false);
		const Common::Array<int16> plainB = decodeClip(kB);
		TS_ASSERT(b && readAll(b) == plainB);
		delete b;
#endif
	}
